/// Országkód-feloldás a napi listához, a verseny- és csapatnézetekhez.
///
/// A zászló nem kézi emoji-tábla: az ISO 3166-1 alpha-2 kódból Unicode
/// regional indicator párokkal számoljuk. A brit hazai nemzetek
/// (Anglia, Skócia, Wales, Észak-Írország) a saját tag-szekvenciás
/// zászlójukat kapják; Észak-Írországnak nincs Unicode-zászlaja, ezért
/// ott a brit zászló jelenik meg. Az ismeretlen kód zászlaja fehér.
public enum CountryCatalog {
    /// Megjelenítendő zászló + magyar országnév.
    public struct Display: Equatable, Sendable {
        public let flag: String
        public let name: String

        public init(flag: String, name: String) {
            self.flag = flag
            self.name = name
        }
    }

    /// Ismeretlen ország zászlaja.
    public static let unknownFlag = "🏳️"

    /// Országkód → zászló és magyar név.
    ///
    /// A `code` lehet ISO 3166-1 alpha-3 vagy alpha-2, brit hazai nemzet
    /// (GB-ENG / GB-SCT / GB-WLS / GB-NIR) vagy labdarúgó-alias
    /// (ENG / SCO / WAL / NIR). Ismeretlen kódnál a zászló fehér, a név
    /// pedig az API-ból kapott `name`, végső esetben a nyers kód.
    public static func display(code: String?, name: String?) -> Display {
        let apiName = name?.trimmingCharacters(in: .whitespacesAndNewlines)
        let providedName = (apiName?.isEmpty == false) ? apiName : nil
        let raw = normalized(code)
        guard let raw, let resolved = resolve(raw) else {
            return Display(flag: unknownFlag, name: providedName ?? raw ?? "Ismeretlen")
        }
        switch resolved {
        case .subdivision(let key):
            return subdivisions[key] ?? Display(flag: unknownFlag, name: providedName ?? key)
        case .iso2(let iso2):
            let name = hungarianNames[iso2] ?? providedName ?? iso2
            return Display(flag: flag(forISO2: iso2), name: name)
        }
    }

    /// ISO alpha-3 (vagy alias) → ISO alpha-2. Ismeretlen kódra `nil`;
    /// brit hazai nemzetnél `GB`.
    public static func iso2(for code: String) -> String? {
        guard let raw = normalized(code) else { return nil }
        switch resolve(raw) {
        case .subdivision: return "GB"
        case .iso2(let iso2): return iso2
        case nil: return nil
        }
    }

    /// ISO alpha-2 → zászló, regional indicator párokkal számolva.
    /// Érvénytelen (nem két latin betűs) kódra a fehér zászló.
    public static func flag(forISO2 code: String) -> String {
        let upper = code.trimmingCharacters(in: .whitespacesAndNewlines).uppercased()
        guard upper.count == 2 else { return unknownFlag }
        var flag = ""
        for scalar in upper.unicodeScalars {
            guard scalar.value >= 65, scalar.value <= 90,
                  let indicator = Unicode.Scalar(0x1F1E6 + scalar.value - 65) else {
                return unknownFlag
            }
            flag.unicodeScalars.append(indicator)
        }
        return flag
    }

    /// ISO alpha-2 → magyar országnév, ha ismert.
    public static func hungarianName(forISO2 code: String) -> String? {
        hungarianNames[code.trimmingCharacters(in: .whitespacesAndNewlines).uppercased()]
    }

    // MARK: - Feloldás

    private enum Resolved {
        case subdivision(String)
        case iso2(String)
    }

    private static func normalized(_ code: String?) -> String? {
        guard let code else { return nil }
        let trimmed = code.trimmingCharacters(in: .whitespacesAndNewlines).uppercased()
        return trimmed.isEmpty ? nil : trimmed
    }

    private static func resolve(_ code: String) -> Resolved? {
        if subdivisions[code] != nil { return .subdivision(code) }
        if let canonical = subdivisionAliases[code] { return .subdivision(canonical) }
        if let iso2 = iso3Aliases[code] ?? iso3ToISO2[code] { return .iso2(iso2) }
        if code.count == 2, hungarianNames[code] != nil { return .iso2(code) }
        return nil
    }

